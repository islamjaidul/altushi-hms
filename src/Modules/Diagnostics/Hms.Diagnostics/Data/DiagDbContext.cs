    public string PublicToken { get; set; } = "";
}

/// <summary>Mints <see cref="TestOrder.PublicToken"/> values: 16 random bytes as 32 hex chars.</summary>
public static class PublicToken
{
    public const int Length = 32;

    public static string New() => Convert.ToHexStringLower(
        System.Security.Cryptography.RandomNumberGenerator.GetBytes(Length / 2));

    /// <summary>What the public lookup treats as its key: trimmed, lowercased, or null when the
    /// input cannot possibly be a token — the caller answers exactly as it would for a miss.</summary>
    public static string? Normalise(string? input)
    {
        var t = input?.Trim().ToLowerInvariant();
        return t is { Length: Length } && t.All(char.IsAsciiHexDigitLower) ? t : null;
    }
}

